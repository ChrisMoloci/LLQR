describe("Auto encode data without mode switching", () => {
    for (const [key, value] of Object.entries(testData)) {
        it(`Should correctly auto encode data: "${key}"`, () => {
            // Call the auto encoding function without mode switching
            const segments = encodeWithSingleMode(key, value.mode as DataEncodingMode);

            // There should be only one segment
            expect(segments.length).toBe(1);

            // The char count should match the input data length
            expect(segments[0]!.encodedData.length).toBe(value.expectedResult.length);

            // The encoding mode should match the expected mode
            expect(segments[0]!.encodingMode).toBe(value.mode);

            // The encoded data should match the expected result
            expect(segments[0]!.encodedData).toEqual(value.expectedResult);
        });
    }
});